
public class DotCuuTro {
	private String maDoi;
	private String tenDoi;
	private int soLuongNhanSu;
	public DotCuuTro(String maDoi, String tenDoi, int soLuongNhanSu) {
		super();
		this.maDoi = maDoi;
		this.tenDoi = tenDoi;
		this.soLuongNhanSu = soLuongNhanSu;
	}
	public String getMaDoi() {
		return maDoi;
	}
	public void setMaDoi(String maDoi) {
		this.maDoi = maDoi;
	}
	public String getTenDoi() {
		return tenDoi;
	}
	public void setTenDoi(String tenDoi) {
		this.tenDoi = tenDoi;
	}
	public int getSoLuongNhanSu() {
		return soLuongNhanSu;
	}
	public void setSoLuongNhanSu(int soLuongNhanSu) {
		this.soLuongNhanSu = soLuongNhanSu;
	}
	

}
